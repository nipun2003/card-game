package com.nipunapps.cardgame.games.dragontiger.enums;

/**
 * Enumeration of possible betting options in the Dragon Tiger game.
 */
public enum DragonTigerBetOption {

    /**
     * Betting on the Dragon side.
     */
    DRAGON,

    /**
     * Betting on the Tiger side.
     */
    TIGER,

    /**
     * Betting on a tie outcome between Dragon and Tiger.
     */
    TIE
}
